const assert = require("node:assert/strict");
const {balancedOverview, selectClaims} = require("../assets/worldwatch-views.js");
const regions = ["europe", "africa", "asia", "global"].map(id => ({id}));
const item = (id, region, priority = 50, state = "CREDIBLE REPORT", conflict = null, domain = "WAR") => ({id, watch_priority: priority, state, domains: [domain], worldwatch: {primary_region: region, regions: [region], conflicts: conflict ? [conflict] : []}});
const claims = Array.from({length: 100}, (_, i) => item(`e${i}`, "europe", 100 - i, "CREDIBLE REPORT", "ukraine"));
claims.push(item("flood", "europe", 1, "CONFIRMED", null, "CLIMATE"));
claims.push(...["africa", "asia", "global"].flatMap(region => Array.from({length: 10}, (_, i) => item(`${region}${i}`, region, 5 - i))));
const original = JSON.stringify(claims);
const overview = balancedOverview(claims, regions, 24);
assert.equal(overview.length, 24);
assert.equal(new Set(overview.map(claim => claim.id)).size, 24);
for (const region of regions) assert.equal(overview.filter(claim => claim.worldwatch.primary_region === region.id).length, 6);
assert(overview.some(claim => claim.id === "flood"), "overview should include a different topic in a busy region");
assert.equal(JSON.stringify(claims), original, "selection must not mutate claims or scores");
const regional = selectClaims(claims, regions, {region: "europe"});
assert.equal(regional.length, 101, "region view must not have the old 80-card cutoff");
assert.deepEqual(regional.map(claim => claim.id), claims.filter(claim => claim.worldwatch.regions.includes("europe")).map(claim => claim.id));
assert.equal(selectClaims(claims, regions, {region: "europe", conflict: "ukraine"}).length, 100);
assert.deepEqual(selectClaims(claims, regions, {state: "CONFIRMED"}).map(claim => claim.id), ["flood"]);
assert.deepEqual(selectClaims(claims, regions, {region: "africa", state: "CONFIRMED"}), []);
assert.deepEqual(balancedOverview([], regions), []);
const crossRegion = item("cross", "europe");
crossRegion.worldwatch.regions.push("asia");
assert.equal(balancedOverview([crossRegion], regions).length, 1, "cross-region stories get only one overview slot");
assert.equal(selectClaims([crossRegion], regions, {region: "asia"}).length, 1);
console.log("WORLDWATCH view tests passed: balanced selection, topics, filters, scores, empty views and uncapped regional browsing");
